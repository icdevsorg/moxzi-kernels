/// The signing the kernel used until 2026-10-23.
fn sign_before(d: &NonZeroScalar, h: &[u8; 32]) -> Option<[u8; 64]> {
    let z = <Scalar as Reduce<U256>>::reduce_bytes(FieldBytes::from_slice(h)).to_bytes();
    let (sig, _) = (**d).try_sign_prehashed_rfc6979::<Sha256>(&z, &[]).ok()?;
    Some(sig.to_bytes().as_slice().try_into().unwrap())
}

#[test]
fn sign_is_sign() {
    let mut rng = Rng(5);
    let mut digests: Vec<[u8; 32]> = vec![[0; 32], [0xff; 32]];
    let n = hex("ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551");
    let mut n1 = n.clone(); n1[31] -= 1;
    let mut n2 = n.clone(); n2[31] += 1;
    for v in [n, n1, n2] { digests.push(v.try_into().unwrap()) }
    let mut keys: Vec<NonZeroScalar> = edge_scalars().into_iter().filter_map(|k| Option::from(NonZeroScalar::new(k))).take(iters(60, 6)).collect();
    for _ in 0..iters(1_000, 1) { keys.push(NonZeroScalar::new(rng.scalar()).unwrap()) }
    for (i, d) in keys.iter().enumerate() {
        let h = if i < digests.len() * 12 { digests[i % digests.len()] } else { rng.bytes() };
        assert_eq!(ops::sign_prehash(d, &h), sign_before(d, &h));
    }
}

/// verify_prehash end to end on the branches random signatures never reach (x(R) >= n has
/// probability ~2^-128, u1 = 0 needs a digest = 0 mod n): valid signatures built backwards from
/// a chosen R. With u1 = a, u2 = b: Q = b^-1 (R - aG), s = r / b, z = a s, so u1 G + u2 Q = R.
#[test]
fn verify_edge_branches() {
    let n = U256::from_be_slice(&hex("ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551"));
    let n_bytes: [u8; 32] = n.to_be_byte_array().into();
    let g = ProjectivePoint::GENERATOR;
    let mut rng = Rng(9);
    let (mut high_x, mut zero_u1) = (0, 0);
    // (R, r): points with x = n + k (r = k), and ordinary points.
    let mut rs: Vec<(ProjectivePoint, Scalar)> = Vec::new();
    for k in 1u64..iters(120, 8) as u64 {
        let xb: [u8; 32] = n.wrapping_add(&U256::from_u64(k)).to_be_byte_array().into();
        let mut c = [3u8; 33];
        c[1..].copy_from_slice(&xb);
        if let Ok(p) = PublicKey::from_sec1_bytes(&c) { rs.push((p.to_projective(), Scalar::from(k))) }
    }
    assert!(rs.len() > iters(20, 1));
    if cfg!(miri) { rs.truncate(2) } // each class stays: x >= n with u1 = 0 and u1 != 0
    let found = rs.len();
    for _ in 0..iters(20, 1) {
        let p = g * rng.scalar();
        rs.push((p, <Scalar as Reduce<U256>>::reduce_bytes(&p.to_affine().x())));
    }
    for (i, (big_r, r)) in rs.iter().enumerate() {
        let b = rng.scalar();
        let b_inv = b.invert().unwrap();
        // a = 0 (u1 = 0) for every third, so the digest is 0 mod n.
        let a = if i % 3 == 0 { Scalar::ZERO } else { rng.scalar() };
        let q = PublicKey::from_affine(((*big_r - g * a) * b_inv).to_affine()).unwrap();
        let s = *r * b_inv;
        let sig = Signature::from_scalars(*r, s).unwrap();
        let z: [u8; 32] = (a * s).to_bytes().into();
        let mut digests = vec![z];
        if a == Scalar::ZERO { digests.push(n_bytes) } // n reduces to 0 too
        for h in digests {
            let vk = VerifyingKey::from(&q);
            assert!(vk.verify_prehash(&h, &sig).is_ok(), "the reference must accept the constructed signature");
            assert!(ops::verify_prehash(&q, &h, &sig), "R = {big_r:?}");
            // r + 1 and the other s: the reference and the kernel agree.
            let sig2 = Signature::from_scalars(*r + Scalar::ONE, s).unwrap();
            assert_eq!(ops::verify_prehash(&q, &h, &sig2), vk.verify_prehash(&h, &sig2).is_ok());
            let sig3 = Signature::from_scalars(*r, -s).unwrap();
            assert_eq!(ops::verify_prehash(&q, &h, &sig3), vk.verify_prehash(&h, &sig3).is_ok());
            if i < found { high_x += 1 }
            if a == Scalar::ZERO { zero_u1 += 1 }
        }
    }
    assert!(high_x > iters(20, 1) && zero_u1 > iters(10, 1));
}

#[test]
fn verify_is_verify() {
    let mut rng = Rng(6);
    let mut accepted = 0;
    for i in 0..iters(1_500, 2) as u64 {
        let d = NonZeroScalar::new(rng.scalar()).unwrap();
        let key = PublicKey::from_secret_scalar(&d);
        let vk = VerifyingKey::from(&key);
        let h = rng.bytes();
        let sig = Signature::from_slice(&sign_before(&d, &h).unwrap()).unwrap();
        let mut sigs = vec![sig, sig.normalize_s().unwrap_or(sig)];
        let (r, s) = sig.split_scalars();
        sigs.push(Signature::from_scalars(*r, -*s).unwrap()); // the other S
        let mut b = sig.to_bytes(); b[(i % 64) as usize] ^= 1 << (i % 8);
        if let Ok(x) = Signature::from_slice(&b) { sigs.push(x) }
        sigs.push(Signature::from_scalars(rng.scalar(), rng.scalar()).unwrap());
        let mut hs = vec![h];
        let mut h2 = h; h2[(i % 32) as usize] ^= 1; hs.push(h2);
        for sg in &sigs {
            for hh in &hs {
                let new = ops::verify_prehash(&key, hh, sg);
                assert_eq!(new, vk.verify_prehash(hh, sg).is_ok());
                accepted += new as u32;
            }
        }
        // The wrong key.
        let other = PublicKey::from_secret_scalar(&NonZeroScalar::new(rng.scalar()).unwrap());
        assert_eq!(ops::verify_prehash(&other, &h, &sig), VerifyingKey::from(&other).verify_prehash(&h, &sig).is_ok());
    }
    assert!(accepted >= 3 * iters(1_500, 2) as u32);
}
