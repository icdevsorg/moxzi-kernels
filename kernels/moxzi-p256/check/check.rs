struct Rng(u64);
impl Rng {
    fn bytes(&mut self) -> [u8; 32] {
        self.0 += 1;
        Sha256::digest(self.0.to_le_bytes()).into()
    }
    fn scalar(&mut self) -> Scalar {
        <Scalar as Reduce<U256>>::reduce_bytes(&self.bytes().into())
    }
}

/// Scalars that stress carries and digit patterns: small, n - small, powers of two, runs.
fn edge_scalars() -> Vec<Scalar> {
    let mut v = vec![Scalar::ZERO];
    // Under Miri every class below stays with one or two members (ops.rs has no unsafe code: Miri
    // checks the dependencies' unsafe code it reaches, and each reference multiplication is
    // ~10 s of Miri): small values and n - small, powers of two at the ends and the middle.
    for i in 1..40u64 { if !cfg!(miri) || matches!(i, 1 | 2) { v.push(Scalar::from(i)); v.push(-Scalar::from(i)); } }
    let mut p = Scalar::ONE;
    for e in 0..256 {
        if !cfg!(miri) || matches!(e, 0 | 128 | 255) { v.push(p); v.push(p - Scalar::ONE); v.push(-p); }
        p = p.double();
    }
    for byte in [0x00u8, 0x0f, 0xf0, 0x55, 0xaa, 0xff, 0x80, 0x01] {
        if cfg!(miri) && !matches!(byte, 0x55 | 0xff) { continue }
        v.push(<Scalar as Reduce<U256>>::reduce_bytes(&[byte; 32].into()));
    }
    let h = Scalar::from_repr(FieldBytes::clone_from_slice(&hex("7fffffff800000007fffffffffffffffde737d56d38bcf4279dce5617e3192a8"))).unwrap();
    v.extend([h, h + Scalar::ONE, h - Scalar::ONE]); // around n/2
    v
}

fn hex(s: &str) -> Vec<u8> { (0..s.len()).step_by(2).map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap()).collect() }

/// `native` cases natively, `miri` under Miri (crypto under Miri runs ~10^4 times slower; every
/// class of edge case stays, see `edge_scalars`).
const fn iters(native: usize, miri: usize) -> usize { if cfg!(miri) { miri } else { native } }

fn enc(p: &ProjectivePoint) -> [u8; 64] {
    p.to_affine().to_encoded_point(false).as_bytes()[1..].try_into().unwrap()
}

fn row(s: &mut String, b: &[u8; 64]) {
    s.push_str("[");
    for (i, x) in b.iter().enumerate() { if i > 0 { s.push_str(", ") } write!(s, "0x{x:02x}").unwrap() }
    s.push_str("]");
}

/// tables.rs as p256's arithmetic computes it.
fn tables_source() -> String {
    let (tables_n, rows) = (4usize, 16usize);
    let pow2 = |e: usize| { let mut p = ProjectivePoint::GENERATOR; for _ in 0..e { p = p.double() } p };
    let mut s = String::from("//! Static tables for ops.rs. Generated by ../../check (MOXZI_WRITE_TABLES=1 cargo test\n//! --release); its tests check every point against p256's arithmetic. Do not edit.\n\n");
    s.push_str("/// The comb of ops::mul_g: COMB[t][d - 1] = sum over the bits c of d of 2^(ROWS*t + 64*c) G,\n/// as x || y (big-endian).\n");
    writeln!(s, "pub const COMB_TABLES: usize = {tables_n};\npub const COMB_ROWS: usize = {rows};").unwrap();
    writeln!(s, "pub static COMB: [[[u8; 64]; 15]; {tables_n}] = [").unwrap();
    for t in 0..tables_n {
        let basis: Vec<ProjectivePoint> = (0..4).map(|c| pow2(rows * t + 64 * c)).collect();
        s.push_str("    [\n");
        for d in 1..16usize {
            let mut p = ProjectivePoint::IDENTITY;
            for c in 0..4 { if d >> c & 1 == 1 { p += basis[c] } }
            s.push_str("        "); row(&mut s, &enc(&p)); s.push_str(",\n");
        }
        s.push_str("    ],\n");
    }
    s.push_str("];\n\n/// G, 3G, 5G, ..., 127G for ops::lincomb_g's width-8 NAF of u1: x then y, big-endian u64\n/// words (ops turns them into field elements at compile time).\npub const ODD_G_WIDTH: u32 = 8;\npub const ODD_G: [[u64; 8]; 64] = [\n");
    for i in 0..64u64 {
        let e = enc(&(ProjectivePoint::GENERATOR * Scalar::from(2 * i + 1)));
        let w: Vec<String> = (0..8).map(|j| format!("0x{:016x}", u64::from_be_bytes(e[8 * j..8 * j + 8].try_into().unwrap()))).collect();
        writeln!(s, "    [{}],", w.join(", ")).unwrap();
    }
    s.push_str("];\n");
    s
}

#[test]
#[cfg_attr(miri, ignore = "reads tables.rs from disk and regenerates it with the reference crate: native runs check it")]
fn tables_are_current() {
    let want = tables_source();
    let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../rust/src/tables.rs");
    if std::env::var("MOXZI_WRITE_TABLES").is_ok() { std::fs::write(path, &want).unwrap() }
    assert!(std::fs::read_to_string(path).unwrap() == want, "tables.rs is stale: MOXZI_WRITE_TABLES=1");
}

#[test]
fn mul_g_is_mul_by_generator() {
    let mut rng = Rng(1);
    let mut ks = edge_scalars();
    for _ in 0..iters(3_000, 2) { ks.push(rng.scalar()) }
    for k in ks { assert_eq!(ops::mul_g(&k), ProjectivePoint::mul_by_generator(&k), "{k:?}") }
}

#[test]
fn wnaf_digits() {
    let mut rng = Rng(2);
    let mut ks = edge_scalars();
    for _ in 0..iters(3_000, 2) { ks.push(rng.scalar()) }
    for k in ks {
        for w in 2..=7u32 {
            let d = ops::wnaf(&k, w);
            let mut sum = Scalar::ZERO;
            let mut since = w; // digits since the last non-zero one
            for i in (0..258).rev() {
                sum = sum.double();
                let x = d[i] as i64;
                if x != 0 {
                    assert!(x % 2 != 0 && x.abs() < 1 << (w - 1), "{x}");
                    since = 0;
                } else { since += 1 }
                sum += if x >= 0 { Scalar::from(x as u64) } else { -Scalar::from((-x) as u64) };
            }
            let _ = since;
            assert_eq!(sum, k);
            // At least w-1 zeros after every non-zero digit.
            for i in 0..258 { if d[i] != 0 { for j in 1..w as usize { if i + j < 258 { assert_eq!(d[i + j], 0) } } } }
        }
    }
}

/// A Jacobian point of ops as a p256 point.
fn proj(j: &ops::Jac) -> ProjectivePoint {
    if j.is_infinity() { return ProjectivePoint::IDENTITY }
    let zi = j.z.invert().unwrap();
    let (x, y) = (j.x * zi.square(), j.y * zi.square() * zi);
    let mut b = [0u8; 65];
    b[0] = 4;
    b[1..33].copy_from_slice(&x.to_bytes());
    b[33..].copy_from_slice(&y.to_bytes());
    ProjectivePoint::from_encoded_point(&p256::EncodedPoint::from_bytes(b).unwrap()).unwrap()
}

/// The same point with Z = l (X l^2, Y l^3, l).
fn jac(p: &ProjectivePoint, l: &p256::FieldElement) -> ops::Jac {
    let (x, y) = ops::coordinates(&p.to_affine());
    ops::Jac { x: x * l.square(), y: y * l.square() * l, z: *l }
}

#[test]
fn jacobian_formulas() {
    let mut rng = Rng(7);
    let g = ProjectivePoint::GENERATOR;
    let fe = |r: &mut Rng| loop { if let Some(f) = Option::from(p256::FieldElement::from_bytes(&r.bytes().into())) { if !bool::from(p256::FieldElement::is_zero(&f)) { break f } } };
    let inf = ops::Jac::INFINITY;
    for i in 0..iters(2_000, 4) {
        let p = g * rng.scalar();
        let q = match i % 4 { 0 => p, 1 => -p, 2 => p.double(), _ => g * rng.scalar() };
        if bool::from(p.is_identity()) || bool::from(q.is_identity()) { continue }
        let (jp, jq) = (jac(&p, &fe(&mut rng)), jac(&q, &fe(&mut rng)));
        assert_eq!(proj(&jp), p);
        assert_eq!(proj(&jp.double()), p.double());
        assert_eq!(proj(&jp.add(&jq)), p + q);
        let (qx, qy) = ops::coordinates(&q.to_affine());
        assert_eq!(proj(&jp.add_affine(&qx, &qy)), p + q);
        assert_eq!(proj(&inf.add(&jq)), q);
        assert_eq!(proj(&jp.add(&inf)), p);
        assert_eq!(proj(&inf.add_affine(&qx, &qy)), q);
        assert!(inf.double().is_infinity());
    }
}

#[test]
fn x_mod_n() {
    // Points whose x is in [n, p): r = x - n must match, as reduce(x) == r does.
    let n = U256::from_be_slice(&hex("ffffffff00000000ffffffffffffffffbce6faada7179e84f3b9cac2fc632551"));
    let mut found = 0;
    let mut rng = Rng(8);
    for k in 0u64..iters(200, 12) as u64 {
        let xb: [u8; 32] = n.wrapping_add(&U256::from_u64(k)).to_be_byte_array().into();
        let mut c = [2u8; 33];
        c[1..].copy_from_slice(&xb);
        let Ok(p) = PublicKey::from_sec1_bytes(&c) else { continue };
        found += 1;
        let r = <Scalar as Reduce<U256>>::reduce_bytes(&xb.into());
        assert_eq!(r, Scalar::from(k));
        let j = jac(&p.to_projective(), &p256::FieldElement::from_u64(3 + k));
        if k > 0 { assert!(ops::x_mod_n_is(&j, &r)) }
        assert!(!ops::x_mod_n_is(&j, &(r + Scalar::ONE)));
    }
    assert!(found > iters(50, 2));
    for _ in 0..iters(2_000, 2) {
        let p = ProjectivePoint::GENERATOR * rng.scalar();
        let r = <Scalar as Reduce<U256>>::reduce_bytes(&p.to_affine().x());
        let j = jac(&p, &p256::FieldElement::from_u64(7));
        assert!(ops::x_mod_n_is(&j, &r) == !bool::from(r.is_zero()));
        assert!(!ops::x_mod_n_is(&j, &(r + Scalar::ONE)));
    }
    assert!(!ops::x_mod_n_is(&ops::Jac::INFINITY, &Scalar::ONE));
}

#[test]
fn lincomb_is_two_multiplications() {
    let mut rng = Rng(3);
    let edges = edge_scalars();
    let g = ProjectivePoint::GENERATOR;
    let mut qs = vec![g, -g, g.double(), g * Scalar::from(3u64)];
    for _ in 0..iters(30, 1) { qs.push(g * rng.scalar()) }
    for (i, q) in qs.iter().enumerate() {
        for (j, u1) in edges.iter().enumerate().filter(|(j, _)| j % 7 == i % 7).take(iters(usize::MAX, 3)) {
            let u2 = edges[(j * 31 + i) % edges.len()];
            assert_eq!(proj(&ops::lincomb_g(u1, &q.to_affine(), &u2)), g * u1 + *q * u2);
        }
    }
    for _ in 0..iters(1_500, 2) {
        let (u1, u2, x) = (rng.scalar(), rng.scalar(), rng.scalar());
        let q = g * x;
        let qa = q.to_affine();
        assert_eq!(proj(&ops::lincomb_g(&u1, &qa, &u2)), g * u1 + q * u2);
        // u1 = -u2 * x: the sum is the identity.
        assert!(ops::lincomb_g(&(-(u2 * x)), &qa, &u2).is_infinity());
        // u1 = u2 * x: the sum is a doubling.
        assert_eq!(proj(&ops::lincomb_g(&(u2 * x), &qa, &u2)), (q * u2).double());
    }
}

