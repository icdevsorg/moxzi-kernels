// Rewrites the kernel's lib.rs (and the SDK it uses) into modules of this test crate (see
// ../../moxzi-kernel/check/transform.rs), and the Wycheproof RSA-PSS 3072 vectors into Rust
// (so Miri runs them without parsing JSON or reading files).
include!("../../moxzi-kernel/check/transform.rs");

fn main() {
    let here = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let kernels = here.join("../..");
    rewrite(&kernels.join("moxzi-kernel/src/lib.rs"), &out.join("moxzi-kernel"), &Rewrite { module: "moxzi_kernel", renames: &[], sdk_module: false });
    rewrite(&kernels.join("moxzi-rsa/rust/src/lib.rs"), &out.join("k_rsa"), &Rewrite { module: "k_rsa", renames: &[], sdk_module: true });

    let vectors = here.join("vectors/wycheproof-rsa_pss_3072_sha256_mgf1_32.json");
    println!("cargo:rerun-if-changed={}", vectors.display());
    let w: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(&vectors).unwrap()).unwrap();
    let mut s = String::from("// Generated by build.rs from wycheproof-rsa_pss_3072_sha256_mgf1_32.json.\n");
    s.push_str("pub struct Group { pub n: &'static str, pub e: &'static str, pub tests: &'static [Test] }\n");
    s.push_str("pub struct Test { pub id: u64, pub comment: &'static str, pub msg: &'static str, pub sig: &'static str, pub valid: bool }\n");
    s.push_str("pub const GROUPS: &[Group] = &[\n");
    for g in w["testGroups"].as_array().unwrap() {
        assert_eq!(g["sLen"], 32);
        assert_eq!(g["sha"], "SHA-256");
        assert_eq!(g["mgfSha"], "SHA-256");
        let key = &g["publicKey"];
        s.push_str(&format!("  Group {{ n: {:?}, e: {:?}, tests: &[\n", key["modulus"].as_str().unwrap(), key["publicExponent"].as_str().unwrap()));
        for t in g["tests"].as_array().unwrap() {
            let result = t["result"].as_str().unwrap();
            assert!(result == "valid" || result == "invalid", "tcId {}: result {result}", t["tcId"]);
            s.push_str(&format!(
                "    Test {{ id: {}, comment: {:?}, msg: {:?}, sig: {:?}, valid: {} }},\n",
                t["tcId"], t["comment"].as_str().unwrap(), t["msg"].as_str().unwrap(), t["sig"].as_str().unwrap(), result == "valid"
            ));
        }
        s.push_str("  ] },\n");
    }
    s.push_str("];\n");
    std::fs::write(out.join("wycheproof.rs"), s).unwrap();
}
