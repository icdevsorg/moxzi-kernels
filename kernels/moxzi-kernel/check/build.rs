// Rewrites the SDK and every kernel family into modules of this test crate (transform.rs), and
// generates the table of exported functions from each package's `[kernel.functions]`
// declarations: one typed call per export, so a declaration that disagrees with the Rust
// signature does not compile, and an export nobody declared fails the build. Also extracts a
// few Bitcoin vectors (raw transactions and their sighash inputs) for the valid-input calls.
include!("transform.rs");

use std::fmt::Write as _;

struct Family {
    /// The crate directory under kernels/.
    dir: &'static str,
    module: &'static str,
    /// The mops.toml that declares the kernel's functions, relative to kernels/.
    decls: &'static str,
    renames: &'static [(&'static str, &'static str)],
}

const FAMILIES: &[Family] = &[
    Family { dir: "moxzi-base58/rust", module: "k_base58", decls: "moxzi-base58/mops.toml", renames: &[] },
    Family { dir: "moxzi-bech32/rust", module: "k_bech32", decls: "moxzi-bech32/mops.toml", renames: &[] },
    Family { dir: "moxzi-bitcoin/rust", module: "k_bitcoin", decls: "moxzi-bitcoin/mops.toml", renames: &[] },
    Family { dir: "moxzi-bls12-381/rust", module: "k_bls12_381", decls: "moxzi-bls12-381/mops.toml", renames: &[("sha2::", "sha2_09::")] },
    Family { dir: "moxzi-ed25519/rust", module: "k_ed25519", decls: "moxzi-ed25519/mops.toml", renames: &[] },
    Family { dir: "moxzi-hash/rust", module: "k_hash", decls: "moxzi-hash/mops.toml", renames: &[] },
    Family { dir: "moxzi-ml-dsa/rust", module: "k_ml_dsa", decls: "moxzi-ml-dsa/mops.toml", renames: &[] },
    Family { dir: "moxzi-p256/rust", module: "k_p256", decls: "moxzi-p256/mops.toml", renames: &[] },
    Family { dir: "moxzi-rsa/rust", module: "k_rsa", decls: "moxzi-rsa/mops.toml", renames: &[] },
    Family { dir: "moxzi-secp256k1/rust", module: "k_secp256k1", decls: "moxzi-secp256k1/mops.toml", renames: &[] },
    // The Motoko side of this kernel ships in mo:ic-agent; its [kernel.functions] are copied here.
    Family { dir: "ic-agent-bls", module: "k_ic_agent_bls", decls: "ic-agent-bls/kernel/declarations.toml", renames: &[("sha2::", "sha2_09::")] },
];

/// Exports no package declares, with the declaration the kernel's own doc comment gives them.
/// (None today; an entry is `(family, export, declaration line)`.)
const UNDECLARED: &[(&str, &str, &str)] = &[];

struct Decl {
    name: String,
    export: String,
    args: Vec<String>,
    result: String,
    result_bytes: Option<usize>,
}

fn quoted_after<'a>(line: &'a str, key: &str) -> Option<&'a str> {
    let i = line.find(key)? + key.len();
    let rest = &line[i..];
    let rest = &rest[rest.find('"')? + 1..];
    Some(&rest[..rest.find('"')?])
}

fn parse_decl(line: &str) -> Decl {
    let name = quoted_after(line, "").unwrap().to_string();
    let export = quoted_after(line, "export =").expect(line).to_string();
    let result = quoted_after(line, "result =").expect(line).to_string();
    let a = line.find("args = [").expect(line) + 8;
    let args = line[a..a + line[a..].find(']').unwrap()].split(',').map(|s| s.trim().trim_matches('"').to_string()).filter(|s| !s.is_empty()).collect();
    let result_bytes = line.find("result_bytes =").map(|i| line[i + 14..].trim().trim_end_matches('}').trim().parse().expect(line));
    Decl { name, export, args, result, result_bytes }
}

fn declarations(mops: &std::path::Path) -> Vec<Decl> {
    println!("cargo:rerun-if-changed={}", mops.display());
    let text = std::fs::read_to_string(mops).unwrap_or_else(|e| panic!("{}: {e}", mops.display()));
    let mut in_section = false;
    let mut v = Vec::new();
    for line in text.lines() {
        let t = line.trim();
        if t.starts_with('[') {
            in_section = t == "[kernel.functions]";
        } else if in_section && t.starts_with('"') {
            v.push(parse_decl(t));
        }
    }
    v
}

/// The exported function names of a lib.rs.
fn exports(lib: &str) -> Vec<String> {
    let mut v = Vec::new();
    for (i, _) in lib.match_indices("extern \"C\" fn ") {
        let rest = &lib[i + 14..];
        v.push(rest[..rest.find('(').unwrap()].trim().to_string());
    }
    v
}

fn main() {
    let here = std::path::PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let out = std::path::PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let kernels = here.join("..").join("..");
    let mut g = String::from("// Generated by build.rs.\n");
    let sdk = rewrite(&kernels.join("moxzi-kernel/src/lib.rs"), &out.join("moxzi-kernel"), &Rewrite { module: "moxzi_kernel", renames: &[], sdk_module: false });
    let sdk_tests = here.join("sdk_tests.rs");
    println!("cargo:rerun-if-changed={}", sdk_tests.display());
    writeln!(
        g,
        "#[allow(dead_code)] pub mod moxzi_kernel {{ include!({:?}); #[cfg(test)] mod sdk_tests {{ use super::*; include!({:?}); }} }}",
        sdk.display().to_string(),
        sdk_tests.display().to_string()
    )
    .unwrap();
    let mut table = String::from("pub static ENTRIES: &[Entry] = &[\n");
    // The two builds of Cargo.toml's [features]: P-256 alone, or every other family.
    let p256_build = std::env::var_os("CARGO_FEATURE_P256").is_some();
    assert!(!(p256_build && std::env::var_os("CARGO_FEATURE_K256").is_some()), "build with --no-default-features --features p256");
    for f in FAMILIES.iter().filter(|f| (f.module == "k_p256") == p256_build) {
        let src = kernels.join(f.dir).join("src/lib.rs");
        let lib = rewrite(&src, &out.join(f.module), &Rewrite { module: f.module, renames: f.renames, sdk_module: true });
        writeln!(g, "#[allow(dead_code, deprecated, clippy::all)] pub mod {} {{ include!({:?}); }}", f.module, lib.display().to_string()).unwrap();
        let family = f.dir.trim_end_matches("/rust");
        let mut decls = declarations(&kernels.join(f.decls));
        for (fam, _, line) in UNDECLARED {
            if *fam == family {
                decls.push(parse_decl(line));
            }
        }
        let exported = exports(&std::fs::read_to_string(&src).unwrap());
        for e in &exported {
            assert!(decls.iter().any(|d| &d.export == e), "{family}: `{e}` is exported but no package declares it (add it to UNDECLARED in build.rs)");
        }
        for d in &decls {
            assert!(exported.contains(&d.export), "{family}: {} declares `{}`, which lib.rs does not export", d.name, d.export);
            let mut params = Vec::new();
            let mut call = Vec::new();
            let mut kinds = Vec::new();
            for (i, a) in d.args.iter().enumerate() {
                match a.as_str() {
                    "Blob" | "Text" => {
                        params.push("*const u8, usize".to_string());
                        call.push(format!("a[{i}].ptr(), a[{i}].len()"));
                    }
                    "Nat64" | "Bool" => {
                        params.push("u64".to_string());
                        call.push(format!("a[{i}].int()"));
                    }
                    other => panic!("{family} {}: argument kind {other}", d.name),
                }
                kinds.push(format!("Kind::{a}"));
            }
            let (ret, res, tail) = match (d.result.as_str(), d.result_bytes) {
                ("Blob", Some(n)) => {
                    params.push("*mut u8".into());
                    call.push("out".into());
                    ("", format!("Res::Fixed({n})"), "; 0")
                }
                ("Bool", None) => (" -> u32", "Res::Bool".into(), " as u64"),
                ("Blob", None) => (" -> u64", "Res::Blob".into(), ""),
                ("?Blob", None) => (" -> u64", "Res::OptBlob".into(), ""),
                ("Text", None) => (" -> u64", "Res::Text".into(), ""),
                ("?Text", None) => (" -> u64", "Res::OptText".into(), ""),
                (r, b) => panic!("{family} {}: result {r} {b:?}", d.name),
            };
            writeln!(
                table,
                "  Entry {{ family: {family:?}, name: {:?}, export: {:?}, args: &[{}], result: {res}, call: {{ unsafe fn c(a: &[Arg], out: *mut u8) -> u64 {{ let _ = (a, out); let f: unsafe extern \"C-unwind\" fn({}){ret} = crate::{}::{}; f({}){tail} }} c }} }},",
                d.name, d.export, kinds.join(", "), params.join(", "), f.module, d.export, call.join(", ")
            )
            .unwrap();
        }
    }
    table.push_str("];\n");
    g.push_str(&table);
    std::fs::write(out.join("kernels.rs"), g).unwrap();

    // Bitcoin vectors for the valid-input calls (vectors/, from Bitcoin Core and the BIPs): a few
    // of each kind.
    let vectors = here.join("vectors/kernel-family-bitcoin.json");
    println!("cargo:rerun-if-changed={}", vectors.display());
    let w: serde_json::Value = serde_json::from_str(&std::fs::read_to_string(&vectors).unwrap()).unwrap();
    let mut b = String::from("// Generated by build.rs from kernel-family-bitcoin.json.\n");
    b.push_str("pub const SIGHASH_LEGACY: &[(&str, &str, u64, i64, &str)] = &[\n");
    for v in w["sighashLegacy"].as_array().unwrap().iter().take(4) {
        writeln!(b, "  ({:?}, {:?}, {}, {}, {:?}),", v[0].as_str().unwrap(), v[1].as_str().unwrap(), v[2], v[3], v[4].as_str().unwrap()).unwrap();
    }
    b.push_str("];\npub const BIP143: &[(&str, u64, &str, u64, u64, &str)] = &[\n");
    for v in w["bip143"].as_array().unwrap().iter().take(3) {
        writeln!(b, "  ({:?}, {}, {:?}, {}, {}, {:?}),", v["tx"].as_str().unwrap(), v["index"], v["scriptCode"].as_str().unwrap(), v["amount"].as_str().unwrap(), v["hashType"], v["sigHash"].as_str().unwrap()).unwrap();
    }
    let k = &w["bip341"]["keyPathSpending"][0];
    writeln!(b, "];\npub const BIP341_TX: &str = {:?};", k["given"]["rawUnsignedTx"].as_str().unwrap()).unwrap();
    b.push_str("pub const BIP341_UTXOS: &[(&str, u64)] = &[\n");
    for u in k["given"]["utxosSpent"].as_array().unwrap() {
        writeln!(b, "  ({:?}, {}),", u["scriptPubKey"].as_str().unwrap(), u["amountSats"]).unwrap();
    }
    b.push_str("];\npub const BIP341_INPUTS: &[(u64, u64, &str)] = &[\n");
    for i in k["inputSpending"].as_array().unwrap().iter().take(3) {
        writeln!(b, "  ({}, {}, {:?}),", i["given"]["txinIndex"], i["given"]["hashType"], i["intermediary"]["sigHash"].as_str().unwrap()).unwrap();
    }
    b.push_str("];\npub const ADDRESSES: &[(&str, &str, &str)] = &[\n");
    for v in w["keyIoValid"].as_array().unwrap().iter().take(8) {
        writeln!(b, "  ({:?}, {:?}, {:?}),", v[0].as_str().unwrap(), v[1].as_str().unwrap(), v[2].as_str().unwrap()).unwrap();
    }
    b.push_str("];\npub const BIP32_DERIVE: &[(&str, u64, &str)] = &[\n");
    for v in w["bip32"]["derive"].as_array().unwrap().iter().take(3) {
        writeln!(b, "  ({:?}, {}, {:?}),", v[0].as_str().unwrap(), v[1], v[2].as_str().unwrap()).unwrap();
    }
    b.push_str("];\n");
    std::fs::write(out.join("bitcoin_vectors.rs"), b).unwrap();
}
